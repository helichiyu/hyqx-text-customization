"""图文要素与描述生成 Prompt（图文融合交付说明 §4.3.0/§4.3.2–§4.3.5 原文）。"""

COMMON_RULES = """【公共约定】
1. 只输出一个 JSON 对象，不要解释、不要 Markdown 代码块；
2. 只描述图上可见事实，不推理、不补充图外信息、不做证明；
3. 所有文字必须来自图中，不允许编造；
4. 看不清或不确定的内容写入 uncertain 数组，不要猜；
5. 禁止输出 1.0 的置信度，最高 0.98。"""

GEOMETRY_PROMPT = COMMON_RULES + """

请将以下几何图片转换为结构化文本描述。按下列格式输出，不添加推理或证明过程。

输出格式要求：
【图形类型】平面几何图形
【基本构成】列出所有可见图形（正方形、三角形等）及其顶点标注
【辅助元素】描述图中除基本图形外添加的线段、点、平行/垂直/相等标记等
【图形位置关系说明】描述点、线、面的相对位置（内部/外部/交点/左右上下等）

只输出 JSON：
{
  "type": "geometry",
  "subtype": "平面几何图",
  "ocr": [{"text":"2√3","conf":0.0-0.98}],
  "description": {
    "图形类型": "...",
    "基本构成": "...",
    "辅助元素": "...",
    "图形位置关系说明": "..."
  },
  "fieldConfidence": {"图形类型":0.95,"基本构成":0.9,"辅助元素":0.85,"图形位置关系说明":0.8},
  "uncertain": ["..."],
  "confidence": 0.0-0.98
}

【规则】
- 图上没有平行/相等/直角标记时，明确写"图上未见平行、相等、直角或角度标记"；
- 题干文字不纳入描述，只记"图中含题干"；
- 坐标系属于辅助元素。"""

CHART_PROMPT = COMMON_RULES + """

请描述以下统计图表的信息。按下列格式输出。

输出格式要求：
【图表类型】折线图 / 柱状图 / 散点图 / 饼图
【标题】图表标题（若有）
【坐标轴】X轴名称及取值范围（或类别）；Y轴名称及取值范围
【图例】各系列名称（若有）
【数据内容】按系列列出关键数据点（折线图：年份→数值；柱状图：类别→数值；散点图：坐标点列表）
【备注】单位、数据来源、特殊标注等（若有）

只输出 JSON：
{
  "type": "chart",
  "subtype": "折线图/柱状图/散点图/饼图",
  "ocr": [{"text":"2023","conf":0.0-0.98}],
  "axis": {"x":"...","y":"..."},
  "legends": ["..."],
  "series": [{"name":"...","points":[{"x":"2023","y":120}]}],
  "description": {
    "图表类型": "...",
    "标题": "...",
    "坐标轴": "...",
    "图例": "...",
    "数据内容": "...",
    "备注": "..."
  },
  "fieldConfidence": {"图表类型":0.95,"标题":0.9,"坐标轴":0.9,"图例":0.85,"数据内容":0.8,"备注":0.75},
  "uncertain": ["..."],
  "confidence": 0.0-0.98
}

【规则】
- 数值缺失或遮挡时写 null，不估算；
- 饼图没有坐标轴时，坐标轴写"无"；
- 无标题、无图例、无备注时写"无"，不要省略字段。"""

TABLE_PROMPT = COMMON_RULES + """

请将图片中的表格内容转换为结构化文本。按下列格式输出。

输出格式要求：
【表格类型】普通表格 / 三线表
【表头】各列名称（按顺序列出）
【数据行】按行列出单元格内容，空单元格用"（空）"标注
【备注】表格标题、单位、说明等

只输出 JSON：
{
  "type": "table",
  "subtype": "普通表格/三线表",
  "ocr": [{"text":"营收","conf":0.0-0.98}],
  "table": {
    "rows": 8,
    "cols": 4,
    "headerRows": [["年份","营收（亿元）"]],
    "dataRows": [["2023","120"]],
    "merges": []
  },
  "description": {
    "表格类型": "...",
    "表头": "...",
    "数据行": "...",
    "备注": "..."
  },
  "fieldConfidence": {"表格类型":0.95,"表头":0.9,"数据行":0.85,"备注":0.8},
  "uncertain": ["..."],
  "confidence": 0.0-0.98
}

【规则】
- 空单元格统一写"（空）"；
- 合并单元格写入 merges，无法判断时写 uncertain；
- 表格外的标题、单位、注释放入备注，不塞进表头。"""

SCHEMATIC_PROMPT = COMMON_RULES + """

请详细描述以下样例展示图的视觉内容。按下列格式输出。

输出格式要求：
【图片类型】示意图
【整体描述】一句话概括图片主题和场景
【区域划分】按位置（顶部/中部/底部/左上/右下等）描述各区域内容
【视觉元素】颜色、形状、图标、按钮、文字内容等
【空间关系】元素之间的相对位置（上方/下方/左侧/右侧/重叠/包含等）
【提取文字】图中所有可识别的文字（按钮标签、标题、说明等）

只输出 JSON：
{
  "type": "schematic",
  "subtype": "示意图",
  "ocr": [{"text":"采集","conf":0.0-0.98}],
  "nodes": [{"id":"n1","label":"采集","shape":"rect"}],
  "edges": [{"from":"n1","to":"n2","arrow":true,"style":"solid"}],
  "description": {
    "图片类型": "示意图",
    "整体描述": "...",
    "区域划分": "...",
    "视觉元素": "...",
    "空间关系": "...",
    "提取文字": "..."
  },
  "fieldConfidence": {"图片类型":0.9,"整体描述":0.9,"区域划分":0.85,"视觉元素":0.85,"空间关系":0.8,"提取文字":0.8},
  "uncertain": ["..."],
  "confidence": 0.0-0.98
}

【规则】
- 提取文字必须与 OCR 一致，不额外推断；
- 没有连线/箭头时，节点关系写"无可见连线"；
- 颜色只写主色，不猜色值。"""

